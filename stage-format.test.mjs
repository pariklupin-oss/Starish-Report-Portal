import assert from 'node:assert/strict';
import {stageGapSeconds,formatStageDuration,formatStageTimestamp,stageDisplayFields} from './stage-format.js';
import {derived} from './report-model.js';
import {buildReportTable} from './report-table.js';
const oldGap='Thu Mar 01 1900 18:10:00 GMT+0521 (India Standard Time)';
const oldClock='Sat Dec 30 1899 01:14:35 GMT+0521 (India Standard Time)';
assert.equal(formatStageDuration(stageGapSeconds(oldGap)),'1482:10:00');
assert.equal(formatStageDuration(stageGapSeconds(oldClock)),'1:14:35');
assert.equal(formatStageDuration(stageGapSeconds('1507:36:00')),'1507:36:00');
assert.equal(formatStageDuration(stageGapSeconds('-0:20:59')),'-0:20:59');
assert.equal(formatStageDuration(stageGapSeconds(0)), '0:00:00');
assert.equal(stageGapSeconds(''),null);
assert.equal(stageGapSeconds(null),null);
assert.equal(stageGapSeconds('2026-10-23 10:00:00'),null);
assert.equal(stageGapSeconds('bad data'),null);
assert.equal(stageGapSeconds(null,'-0.35'),-1260);
assert.equal(formatStageDuration(stageGapSeconds(1.5)),'36:00:00');
assert.equal(formatStageTimestamp('2026-10-23 06:37:02'),'23-10-2026 06:37:02');
assert.equal(formatStageTimestamp('2026-10-22T20:00:00Z'),'23-10-2026 01:30:00');
assert.equal(formatStageTimestamp(oldClock),'01:14:35');
assert.equal(formatStageTimestamp('01:20'),'01:20');
assert.equal(formatStageTimestamp(46318.5),'23-10-2026 12:00:00');
const fields={'GAP-1 (Production and Loading)':oldGap,'GAP-2 (Loading and Billing)':'-0:20:59','GAP-2 (hrs)':'-0.35','GAP-3 (Billing and Gate Out)':'','OQC End':'01:20','Invoice Time':'23-10-2026 06:37:02'};
const r={id:'r1',type:'Stage Report',date:'2026-10-23',shift:'Daily',fields};
const original=JSON.stringify(r);
const out=derived(r);
assert.equal(out['GAP-1 (Production and Loading)'],'1482:10:00');
assert.equal(out['GAP-2 (Loading and Billing)'],'-0:20:59');
assert.equal(out['GAP-2 (hrs)'],'-0.35');
assert.equal(out['GAP-3 (Billing and Gate Out)'],'');
assert.equal(JSON.stringify(r),original);
const table=buildReportTable('Stage Report',[r]);
assert.equal(table.rows[0].values['GAP-1 (Production and Loading)'],'1482:10:00');
assert.equal(table.rows[0].values['Invoice Time'],'23-10-2026 06:37:02');
assert.equal(derived({type:'Water Meter',fields:{'Opening Reading':'10','Closing Reading':'15','Reading Multiplier':'2'}})['Consumption (litres)'],'10.00');
assert.equal(stageDisplayFields({'GAP-1 (hrs)':'2.5'})['GAP-1 (Production and Loading)'],'2:30:00');
assert.equal(stageGapSeconds('1900-02-31 00:00:00'),null);
console.log('Stage date/duration regression checks passed (26 assertions).');
