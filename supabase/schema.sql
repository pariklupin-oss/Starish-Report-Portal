-- Starish Report & Task Portal — staging schema
-- Apply only to a separate Supabase test project first.
-- Passwords are managed by Supabase Auth; never copy portal passwords into these tables.

create extension if not exists pgcrypto;

do $$ begin
  create type public.portal_role as enum (
    'owner', 'admin', 'manager', 'hr_head', 'maintenance_head', 'maintenance', 'employee'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.task_status as enum (
    'Pending', 'In Progress', 'Completed', 'Approved'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.complaint_status as enum (
    'Open', 'Assigned', 'In Progress', 'On Hold', 'Completed', 'Closed'
  );
exception when duplicate_object then null; end $$;

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  employee_code text unique,
  full_name text not null,
  mobile text,
  department text,
  role public.portal_role not null default 'employee',
  is_active boolean not null default true,
  -- Preserve portal section/form/entry permissions during migration.
  access jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  -- Use one row per assignee; shared shift tasks can share this group id.
  task_group_id uuid not null default gen_random_uuid(),
  title text not null,
  description text,
  department text,
  assigned_to uuid not null references public.users(id),
  assigned_by uuid references public.users(id),
  due_date date not null default current_date,
  status public.task_status not null default 'Pending',
  priority text not null default 'Normal'
    check (priority in ('Low', 'Normal', 'Medium', 'High', 'Urgent')),
  completion_note text,
  completed_at timestamptz,
  approved_by uuid references public.users(id),
  approved_at timestamptz,
  source text not null default 'portal'
    check (source in ('portal', 'routine', 'excel_import', 'migration')),
  source_key text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.production_reports (
  id uuid primary key default gen_random_uuid(),
  module text not null,
  report_date date not null,
  shift text,
  machine_name text,
  source_sheet text,
  source_row_key text,
  -- Retain each sheet's original columns during migration; typed columns can be added
  -- after actual sheet headers and calculations are inspected.
  payload jsonb not null default '{}'::jsonb,
  created_by uuid references public.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source_sheet, source_row_key)
);

create table if not exists public.maintenance_complaints (
  id uuid primary key default gen_random_uuid(),
  token_no bigint generated by default as identity unique,
  complaint_date timestamptz not null default now(),
  machine_name text not null,
  machine_part text,
  issue_type text not null check (issue_type in ('Electrical', 'Mechanical', 'Other')),
  description text not null,
  spares_availability text,
  posting_no text,
  priority text not null default 'Normal'
    check (priority in ('Normal', 'Urgent')),
  posted_by uuid not null references public.users(id),
  assigned_by uuid references public.users(id),
  assigned_to uuid references public.users(id),
  spares_procured text,
  status public.complaint_status not null default 'Open',
  hold_reason text,
  remarks text,
  completed_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'On Hold' or nullif(trim(hold_reason), '') is not null)
);

create table if not exists public.maintenance_work_logs (
  id uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.maintenance_complaints(id) on delete cascade,
  employee_id uuid not null references public.users(id),
  started_at timestamptz not null,
  ended_at timestamptz,
  note text,
  created_at timestamptz not null default now(),
  check (ended_at is null or ended_at >= started_at)
);

create index if not exists tasks_assigned_due_idx
  on public.tasks (assigned_to, due_date desc);
create index if not exists tasks_group_idx on public.tasks (task_group_id);
create index if not exists production_reports_module_date_idx
  on public.production_reports (module, report_date desc);
create index if not exists production_reports_payload_gin_idx
  on public.production_reports using gin (payload);
create index if not exists complaints_assignee_status_idx
  on public.maintenance_complaints (assigned_to, status, complaint_date desc);
create index if not exists work_logs_employee_idx
  on public.maintenance_work_logs (employee_id, started_at desc);

-- RLS helpers are SECURITY DEFINER to avoid recursive reads of public.users policies.
create or replace function public.current_portal_role()
returns public.portal_role
language sql stable security definer
set search_path = ''
as $$
  select u.role from public.users u
  where u.id = (select auth.uid()) and u.is_active = true
$$;

create or replace function public.has_portal_role(allowed public.portal_role[])
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select coalesce(public.current_portal_role() = any(allowed), false)
$$;

create or replace function public.touch_updated_at()
returns trigger language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end
$$;

drop trigger if exists users_touch_updated_at on public.users;
create trigger users_touch_updated_at before update on public.users
for each row execute function public.touch_updated_at();
drop trigger if exists tasks_touch_updated_at on public.tasks;
create trigger tasks_touch_updated_at before update on public.tasks
for each row execute function public.touch_updated_at();
drop trigger if exists production_reports_touch_updated_at on public.production_reports;
create trigger production_reports_touch_updated_at before update on public.production_reports
for each row execute function public.touch_updated_at();
drop trigger if exists complaints_touch_updated_at on public.maintenance_complaints;
create trigger complaints_touch_updated_at before update on public.maintenance_complaints
for each row execute function public.touch_updated_at();

alter table public.users enable row level security;
alter table public.tasks enable row level security;
alter table public.production_reports enable row level security;
alter table public.maintenance_complaints enable row level security;
alter table public.maintenance_work_logs enable row level security;

-- Users can read their own profile; managers can read the directory.
drop policy if exists users_read_self_or_management on public.users;
create policy users_read_self_or_management on public.users for select to authenticated
using (
  id = (select auth.uid()) or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);
-- Profile provisioning/role changes are server-side only. Do not allow self role edits.

drop policy if exists tasks_read_assigned_or_management on public.tasks;
create policy tasks_read_assigned_or_management on public.tasks for select to authenticated
using (
  assigned_to = (select auth.uid()) or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);
drop policy if exists tasks_update_assigned_or_management on public.tasks;
create policy tasks_update_assigned_or_management on public.tasks for update to authenticated
using (
  assigned_to = (select auth.uid()) or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
)
with check (
  (
    assigned_to = (select auth.uid())
    and status <> 'Approved'::public.task_status
  ) or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);
drop policy if exists tasks_insert_management on public.tasks;
create policy tasks_insert_management on public.tasks for insert to authenticated
with check (
  public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);

drop policy if exists reports_read_management on public.production_reports;
create policy reports_read_management on public.production_reports for select to authenticated
using (public.has_portal_role(
  array['owner','admin','manager']::public.portal_role[]
));
drop policy if exists reports_write_management on public.production_reports;
create policy reports_write_management on public.production_reports for all to authenticated
using (public.has_portal_role(
  array['owner','admin','manager']::public.portal_role[]
))
with check (public.has_portal_role(
  array['owner','admin','manager']::public.portal_role[]
));

drop policy if exists complaints_read_participants on public.maintenance_complaints;
create policy complaints_read_participants on public.maintenance_complaints for select to authenticated
using (
  posted_by = (select auth.uid())
  or assigned_to = (select auth.uid())
  or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);
drop policy if exists complaints_create_authenticated on public.maintenance_complaints;
create policy complaints_create_authenticated on public.maintenance_complaints for insert to authenticated
with check (posted_by = (select auth.uid()));
drop policy if exists complaints_update_maintenance_or_management on public.maintenance_complaints;
create policy complaints_update_maintenance_or_management on public.maintenance_complaints for update to authenticated
using (
  assigned_to = (select auth.uid())
  or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
)
with check (
  assigned_to = (select auth.uid())
  or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);

drop policy if exists work_logs_read_participants on public.maintenance_work_logs;
create policy work_logs_read_participants on public.maintenance_work_logs for select to authenticated
using (
  employee_id = (select auth.uid())
  or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);
drop policy if exists work_logs_write_self_or_head on public.maintenance_work_logs;
create policy work_logs_write_self_or_head on public.maintenance_work_logs for all to authenticated
using (
  employee_id = (select auth.uid())
  or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
)
with check (
  employee_id = (select auth.uid())
  or public.has_portal_role(
    array['owner','admin','manager','maintenance_head']::public.portal_role[]
  )
);

